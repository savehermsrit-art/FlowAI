import {chromium} from '@playwright/test';
const browser=await chromium.launch();const page=await browser.newPage();
page.on('pageerror',e=>console.log('JS_ERROR',e.message));
page.on('response',r=>{if(r.url().includes('/api/'))console.log(r.status(),r.url())});
await page.goto('http://localhost:3000');
await page.getByRole('button',{name:'Find my schemes',exact:true}).last().click();
await page.getByLabel('Demo username').fill('diagnostic-user');
await page.getByRole('button',{name:'Get a one-time code'}).click();
await page.getByTestId('development-code').waitFor({timeout:10000});
const code=await page.getByTestId('development-code').textContent();
await page.getByLabel('One-time code',{exact:true}).fill(code.trim());
await page.getByRole('button',{name:'Continue securely'}).click();
await page.getByRole('button',{name:'A · Complete evidence',exact:true}).waitFor({timeout:10000});
console.log('LOGIN_OK');
await page.getByRole('button',{name:'A · Complete evidence',exact:true}).click();
await page.getByLabel('I have read this notice').check();
await page.getByRole('button',{name:'Give consent & continue'}).click();
await page.getByRole('button',{name:'Load fictional sample documents',exact:true}).click();
await page.getByText('Ready to review',{exact:true}).first().waitFor({timeout:30000});
console.log('UPLOAD_OK');
await page.screenshot({path:'../data/diagnostic.png',fullPage:true});
await browser.close();
